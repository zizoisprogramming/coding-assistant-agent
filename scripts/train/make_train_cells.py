"""Writes kaggle/cells_train_12b/ (12B LoRA training notebook) with the tested repo code embedded:
scripts/train/{int4_lora,build_samples,train_sft}.py and scripts/render_traces.py. Re-run after editing any of them.

    python3 scripts/train/make_train_cells.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "kaggle" / "cells_train_12b"
OUT.mkdir(parents=True, exist_ok=True)
code = {name: (ROOT / "scripts" / "train" / name).read_text() for name in ("int4_lora.py", "build_samples.py", "train_sft.py")}
code["render_traces.py"] = (ROOT / "scripts" / "render_traces.py").read_text()

(OUT / "cell1_install.py").write_text((ROOT / "kaggle" / "cells_train_probe" / "cell1.py").read_text().replace(
    "# 1. Install the competition wheelhouse", "# 1. 12B TRAINING (GPU L4x4, competition notebook). Install the competition wheelhouse", 1))

(OUT / "cell2_setup.py").write_text(f'''# 2. Setup: writes the training code to /kaggle/working/train_code and finds the inputs.
#    Generated by scripts/train/make_train_cells.py from the tested repo code.
# Inputs to attach: the competition (wheelhouse), the model google/gemma-4 -> gemma-4-12b-it-qat-w4a16-ct, and the stage B
# output (the notebook version that printed "550 ok": its stage_b_out folder, attached as notebook output or as a
# dataset made from it).
import glob, json, os, subprocess, sys, time
from pathlib import Path

WORKING_DIR = Path('/kaggle/working')
CODE = WORKING_DIR / 'train_code'
CODE.mkdir(parents=True, exist_ok=True)
for name, text in {code!r}.items():
    (CODE / name).write_text(text)

# Training settings (first 12B run; decided with the user: thinking budget 2048 data, mix prompt, 500 train / 50 val)
CONFIG = dict(
    epochs=1.0,        # one pass over the 500 training episodes
    lr=2e-4,           # LoRA SFT; probe showed 1e-3 diverges, 1e-4 learns; cosine to 10%, 8 warmup steps
    r=16, alpha=32,    # same adapter shape as the probes (vLLM loaded it)
    accum=2,           # segments per copy per step (4 copies -> 8 segments per step)
    max_hours=6.0,     # hard stop for training (schedule re-planned to fit); quota on L4x4 counts double
)

_m = sorted(p for p in glob.glob('/kaggle/input/models/google/gemma-4/**/gemma-4-12b-it-qat-w4a16-ct/*', recursive=True)
            if Path(p, 'config.json').exists())
assert _m, 'attach the model google/gemma-4 -> gemma-4-12b-it-qat-w4a16-ct'
MODEL_PATH = Path(_m[-1])
STAGE_B = sorted({{str(Path(p).parent) for p in glob.glob('/kaggle/input/**/stage_b_out/status.jsonl', recursive=True)}})
assert STAGE_B, 'attach the stage B output (the folder stage_b_out with status.jsonl and requests_*.jsonl)'
_ok = sum(1 for d in STAGE_B for l in Path(d, 'status.jsonl').read_text().splitlines() if '"status": "ok"' in l)
print('MODEL_PATH', MODEL_PATH)
print('stage B folders', STAGE_B, '| episodes ok:', _ok, '| request logs:',
      [f"{{p.name}} {{p.stat().st_size / 1e6:.0f}} MB" for d in STAGE_B for p in Path(d).glob('requests_*.jsonl')])
import torch
print('GPUs:', [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())], '| CONFIG', CONFIG)
''')

(OUT / "cell3_samples.py").write_text('''# 3. Training samples: one token sequence per episode segment (split at compactions), loss only on what the model
#    wrote (thinking, tool calls, final message, stop tokens). ~2-5 min on CPU.
SAMPLES = WORKING_DIR / 'samples.pt'
r = subprocess.run([sys.executable, '-u', str(CODE / 'build_samples.py'), '--stage-b', *STAGE_B,
                    '--tokenizer-dir', str(MODEL_PATH), '--out', str(SAMPLES)])
assert r.returncode == 0 and SAMPLES.exists(), 'building the samples failed (see above)'
''')

(OUT / "cell4_fit.py").write_text('''# 4. Memory + speed check on the LONGEST training segment: can one L4 hold a full copy of the 12B (4 copies train in
#    parallel, ~4x faster)? If not, each copy uses 2 GPUs (2 copies). Prints the expected training time.
def probe(g):
    out = WORKING_DIR / 'fit'
    r = subprocess.run([sys.executable, '-u', str(CODE / 'train_sft.py'), '--model', str(MODEL_PATH), '--samples',
                        str(SAMPLES), '--out', str(out), '--probe', '--gpus-per-rank', str(g)],
                       capture_output=True, text=True)
    line = [l for l in r.stdout.splitlines() if l.startswith('PROBE ')]
    if r.returncode != 0 or not line:
        tail = (r.stdout + r.stderr)[-1500:]
        print(f'  {g} GPU(s) per copy: FAILED' + (' (out of memory)' if 'out of memory' in tail.lower() else ''))
        print('  ' + tail.replace('\\n', '\\n  ')[-800:])
        return None
    res = json.loads(line[0][6:])
    print(f"  {g} GPU(s) per copy: OK, {res['tokens']} tokens fwd+bwd in {res['seconds']}s "
          f"({res['tokens_per_s']} tok/s), peak {res['peak_gib']} GiB, loss {res['loss']}")
    return res

n_gpu = torch.cuda.device_count()
fit = probe(1)
GPUS_PER_RANK = 1 if fit and fit['peak_gib'] < 21.0 else 2
if GPUS_PER_RANK == 2:
    print('one GPU is not enough (or too tight): using 2 GPUs per copy')
    fit = probe(2)
    assert fit, 'the 12B does not fit even on 2 GPUs per copy: send me the output above'
RANKS = n_gpu // GPUS_PER_RANK
_s = torch.load(SAMPLES)
_train_tok = sum(len(x['input_ids']) for x in _s if x['split'] == 'train')
_val_tok = sum(len(x['input_ids']) for x in _s if x['split'] == 'val')
_speed = fit['tokens_per_s'] * RANKS * 0.9  # longest segment is the slowest per token; 10% for sync/imbalance
_hours = CONFIG['epochs'] * _train_tok / _speed / 3600 + 3 * _val_tok / (_speed * 3) / 3600
print(f"\\n==> {RANKS} copies x {GPUS_PER_RANK} GPU(s); train {_train_tok / 1e6:.2f}M tokens/epoch; "
      f"expected ~{_hours:.1f} h of training incl. validation (cap {CONFIG['max_hours']} h)")
''')

(OUT / "cell5_train.py").write_text('''# 5. Train. One line per step (loss, running average, lr, grad norm, tokens/s, GPU memory, ETA); validation loss at
#    the start, ~every quarter and at the end; adapter saved at each validation (resumable: re-running this cell
#    continues from the last saved step).
TRAIN_OUT = WORKING_DIR / 'adapter_12b_v1'
cmd = [sys.executable, '-u', '-m', 'torch.distributed.run', '--standalone', f'--nproc_per_node={RANKS}',
       str(CODE / 'train_sft.py'), '--model', str(MODEL_PATH), '--samples', str(SAMPLES), '--out', str(TRAIN_OUT),
       '--gpus-per-rank', str(GPUS_PER_RANK), '--epochs', str(CONFIG['epochs']), '--lr', str(CONFIG['lr']),
       '--r', str(CONFIG['r']), '--alpha', str(CONFIG['alpha']), '--accum', str(CONFIG['accum']),
       '--max-hours', str(CONFIG['max_hours'])]
# NCCL_P2P_DISABLE: gradient sums go through host memory (~0.3 GB/step, <1 s); avoids P2P hangs seen on Kaggle
env = dict(os.environ, PYTORCH_CUDA_ALLOC_CONF='expandable_segments:True', OMP_NUM_THREADS='4', NCCL_P2P_DISABLE='1')
p = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, env=env)
noise = ('Warning', 'warn(', 'Loading weights', 'Compressing', 'it/s]')
for line in p.stdout:
    if line.strip() and not any(n in line for n in noise):
        print(line, end='', flush=True)
print('exit code', p.wait())
''')

(OUT / "cell6_report.py").write_text('''# 6. Report + files to keep: the final adapter (zip), history.json (every step and validation), report.json.
import shutil
hist = json.loads((TRAIN_OUT / 'history.json').read_text())
tr = [h for h in hist if h['type'] == 'train']
va = [h for h in hist if h['type'] == 'val']
report = {
    'copies': RANKS, 'gpus_per_copy': GPUS_PER_RANK, 'config': CONFIG, 'fit_probe': fit,
    'steps': len(tr), 'train_tokens_seen': sum(h['tokens'] for h in tr),
    'first_loss': tr[0]['loss'] if tr else None, 'last_avg_loss': tr[-1]['ema'] if tr else None,
    'validation': [(h['tag'], h['val_loss']) for h in va],
    'train_hours': round(sum(h['seconds'] for h in tr) / 3600, 2), 'peak_mem_gib': max((h['mem_gib'] for h in tr), default=0),
}
(WORKING_DIR / 'report.json').write_text(json.dumps(report, indent=1))
shutil.copy(TRAIN_OUT / 'history.json', WORKING_DIR / 'history.json')
shutil.make_archive(str(WORKING_DIR / 'adapter_12b_v1_final'), 'zip', TRAIN_OUT / 'final')
print(json.dumps(report, indent=1))
print('every 10th step:')
for h in tr[::10] + tr[-1:]:
    print(f"  step {h['step']:4}  loss {h['loss']:.4f}  avg {h['ema']:.4f}  lr {h['lr']:.2e}  grad {h['grad_norm']:.3f}")
print('files: adapter_12b_v1_final.zip (adapter_config.json + adapter_model.safetensors), history.json, report.json')
''')
print("wrote", sorted(p.name for p in OUT.iterdir()))
